/* ═══════════════════════════════════════════════════════════════════
   OFFLINE BLOCK CACHE (IndexedDB)
   ═══════════════════════════════════════════════════════════════════ */
const DB_NAME = 'foxpursuit-maps', DB_VER = 2;  // v2: wipe any partial blocks cached by the broken v60.1
let _db = null;

function idb(){
  if (_db) return Promise.resolve(_db);
  return new Promise((res, rej) => {
    const r = indexedDB.open(DB_NAME, DB_VER);
    r.onupgradeneeded = () => {
      const d = r.result;
      // Fresh start on upgrade: drop any stores from a previous version so a
      // poisoned partial block from the broken v60.1 cannot survive.
      for (const name of Array.from(d.objectStoreNames)) d.deleteObjectStore(name);
      d.createObjectStore('blocks');                    // key: url|blockIndex
      d.createObjectStore('regions', {keyPath:'id'});
      d.createObjectStore('meta');                      // etag etc
    };
    r.onsuccess = () => { _db = r.result; res(_db); };
    r.onerror   = () => rej(r.error);
  });
}
function tx(store, mode, fn){
  return idb().then(d => new Promise((res, rej) => {
    const t = d.transaction(store, mode), s = t.objectStore(store);
    const out = fn(s);
    // fn returns an IDBRequest. Resolve with its .result — which is `undefined`
    // for a missing key. The previous code fell back to returning the IDBRequest
    // object itself when .result was undefined, so getBlock() on an uncached
    // block returned a truthy request object instead of undefined; the caller's
    // `if (!buf)` then treated a missing block as present, skipped the fetch, and
    // stitched an object with no byteLength into a 0-byte buffer -> blank map.
    const isReq = out && typeof out === 'object' && 'result' in out;
    t.oncomplete = () => res(isReq ? out.result : out);
    t.onerror    = () => rej(t.error);
  }));
}
const blockKey = (url, i) => url + '|' + i;
const getBlock = (url,i)   => tx('blocks','readonly',  s => s.get(blockKey(url,i)));
const putBlock = (url,i,b) => tx('blocks','readwrite', s => s.put(b, blockKey(url,i)));
const delBlock = (url,i)   => tx('blocks','readwrite', s => s.delete(blockKey(url,i)));
const getMeta  = (k)       => tx('meta','readonly',    s => s.get(k));
const putMeta  = (k,v)     => tx('meta','readwrite',   s => s.put(v,k));
const allRegions = ()      => tx('regions','readonly', s => s.getAll());
const putRegion  = (r)     => tx('regions','readwrite',s => s.put(r));
const delRegionRec=(id)    => tx('regions','readwrite',s => s.delete(id));

// A "Loading map..." indicator, driven by the number of range requests actually
// in flight. Counted rather than toggled, because many blocks are fetched
// concurrently and a simple on/off would clear on the first one to finish.
let mapFetchesInFlight = 0;
function setMapLoading(on){
  mapFetchesInFlight += on ? 1 : -1;
  if (mapFetchesInFlight < 0) mapFetchesInFlight = 0;
  const el = (typeof document !== 'undefined') && document.getElementById('map-loading');
  if (!el) return;
  // Only show it if the wait is long enough to be worth explaining. A fast
  // connection never sees it; a slow one gets told the app is working.
  if (mapFetchesInFlight > 0){
    if (!el._t) el._t = setTimeout(() => { if (mapFetchesInFlight > 0) el.classList.add('show'); }, 700);
  } else {
    clearTimeout(el._t); el._t = null;
    el.classList.remove('show');
  }
}

async function fetchRange(url, start, end, signal){
  setMapLoading(true);
  try {
  const res = await fetch(url, { headers:{ Range:`bytes=${start}-${end}` }, signal });
  if (!res.ok && res.status !== 206) throw new Error('HTTP ' + res.status);
  const buf = await res.arrayBuffer();
  // How many bytes this range SHOULD contain. For the final (short) block the
  // server returns fewer than requested, and Content-Range tells us the truth.
  let expected = end - start + 1;
  let total = null;
  const cr = res.headers.get('content-range');       // "bytes S-E/TOTAL"
  if (cr){
    const m = /bytes\s+(\d+)-(\d+)\/(\d+|\*)/.exec(cr);
    if (m){
      expected = (+m[2]) - (+m[1]) + 1;
      if (m[3] !== '*') total = +m[3];               // whole-archive size, free of charge
    }
  }
  return { buf, etag: res.headers.get('etag'), complete: buf.byteLength >= expected, total };
  } finally { setMapLoading(false); }
}

/* A pmtiles Source that reads 256 KB blocks, serving them from IndexedDB when
   present and from the network otherwise. Offline, a missing block throws —
   which is correct: that part of the map was never downloaded.

   ABORT HANDLING (important): protomaps-leaflet aborts in-flight reads whenever
   the map's zoom level changes. If that abort reaches a directory read that
   pmtiles' SharedPromiseCache is mid-way through resolving, the cache is left
   holding a rejected promise, and every later read of that directory throws
   "RangeError: Offset is outside the bounds of the DataView" forever — a blank
   map. Our block cache already makes these reads fast and idempotent, so
   cancelling them saves nothing. We therefore do NOT forward the abort signal
   into fetch: reads always run to completion and the directory cache stays
   clean. (We also refuse to cache any short/partial block, as a second guard.) */
class BlockSource {
  constructor(url){ this.url = url; this.cacheOnRead = true; }
  getKey(){ return this.url; }
  async getBytes(offset, length, _ignoredSignal, etag){
    // NB: the abort signal is deliberately ignored — see class comment above.
    const signal = undefined;
    const first = Math.floor(offset / BLOCK);
    const last  = Math.floor((offset + length - 1) / BLOCK);
    const bufs  = [];
    for (let b = first; b <= last; b++){
      let buf = await getBlock(this.url, b);
      if (!buf){
        if (!navigator.onLine) throw new Error('Map area not downloaded for offline use');
        const r = await fetchRange(this.url, b*BLOCK, (b+1)*BLOCK - 1, signal);
        buf = r.buf;
        // Only cache COMPLETE blocks. A truncated (aborted) read is used for
        // this call but never stored, so it cannot poison future reads.
        if (this.cacheOnRead && r.complete) { try { await putBlock(this.url, b, buf); } catch(e){} }
      }
      bufs.push(buf);
    }
    // Concatenate the blocks we fetched. The first block starts at first*BLOCK
    // in the file, so the requested window begins at (offset - first*BLOCK)
    // within the concatenation. slice() clamps to the available length, so a
    // short final block never reads out of bounds.
    const total = bufs.reduce((n,b)=>n+b.byteLength, 0);
    const all = new Uint8Array(total);
    let p = 0;
    for (const b of bufs){ all.set(new Uint8Array(b), p); p += b.byteLength; }
    const from = offset - first*BLOCK;
    const end  = Math.min(from + length, total);
    return { data: all.buffer.slice(from, end), etag };
  }
}

