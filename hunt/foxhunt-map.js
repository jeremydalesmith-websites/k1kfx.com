function lonToX(lon,z){ return Math.floor((lon+180)/360 * Math.pow(2,z)); }
function latToY(lat,z){
  const r = lat*Math.PI/180;
  return Math.floor((1 - Math.log(Math.tan(r) + 1/Math.cos(r))/Math.PI)/2 * Math.pow(2,z));
}
function xToLon(x, z){ return x / Math.pow(2, z) * 360 - 180; }
function yToLat(y, z){ const n = Math.PI - 2 * Math.PI * y / Math.pow(2, z);
  return 180 / Math.PI * Math.atan(0.5 * (Math.exp(n) - Math.exp(-n))); }

// The rectangle where DETAIL (max-zoom) tiles actually exist. A tapered archive
// carries max-zoom tiles only over the hunt box; its wide context tier stops far
// below z-max. Probing z-max existence therefore finds the downloadable detail
// area, which the header (whole-archive bounds) does not reveal. Four edges are
// binary-searched in parallel; result memoised for the page. null = whole map or
// couldn't determine (a plain extract has detail everywhere it covers).
let _detailBounds;
async function detailBounds(){
  if (_detailBounds !== undefined) return _detailBounds;
  try {
    const src = new BlockSource(TILE_URL);
    const p   = new pmtiles.PMTiles(src);
    const h   = await p.getHeader();
    if (h == null || h.minLon == null) { _detailBounds = null; return null; }
    const z = DATA_MAXZOOM;
    const wx = lonToX(h.minLon, z), ex = lonToX(h.maxLon, z);
    const ny = latToY(h.maxLat, z), sy = latToY(h.minLat, z);
    const cx = (wx + ex) >> 1, cy = (ny + sy) >> 1;
    const has = async (x, y) => { try { const t = await p.getZxy(z, x, y); return !!(t && t.data); } catch(e){ return false; } };
    if (!(await has(cx, cy))) { _detailBounds = null; return null; }
    const smallestTrue = async (lo, hi, f) => { while (lo < hi){ const m = (lo + hi) >> 1;      if (await f(m)) hi = m; else lo = m + 1; } return lo; };
    const largestTrue  = async (lo, hi, f) => { while (lo < hi){ const m = (lo + hi + 1) >> 1;  if (await f(m)) lo = m; else hi = m - 1; } return lo; };
    const [minX, maxX, minY, maxY] = await Promise.all([
      smallestTrue(wx, cx, x => has(x, cy)),
      largestTrue (cx, ex, x => has(x, cy)),
      smallestTrue(ny, cy, y => has(cx, y)),
      largestTrue (cy, sy, y => has(cx, y))
    ]);
    _detailBounds = {
      minLat: yToLat(maxY + 1, z), maxLat: yToLat(minY, z),
      minLng: xToLon(minX, z),     maxLng: xToLon(maxX + 1, z)
    };
  } catch (e) { _detailBounds = null; }
  return _detailBounds;
}

function bboxAround(lat, lng, miles){
  const dLat = miles/69.0;
  const dLng = miles/(69.0*Math.cos(lat*Math.PI/180) || 1);
  return { w:lng-dLng, s:lat-dLat, e:lng+dLng, n:lat+dLat };
}
// Which (z,x,y) tiles a region needs. Detail inside the chosen radius; a coarse
// low-zoom shell out to CONTEXT_MILES so the drive there is still mapped. The
// wide shell is nearly free — the bytes are almost all in the deep zooms.
function tilesFor(lat, lng, miles){
  const out = [];
  const inner = bboxAround(lat,lng,miles), outer = bboxAround(lat,lng,CONTEXT_MILES);
  for (let z=0; z<=DATA_MAXZOOM; z++){
    const b = (z<=CONTEXT_ZOOM) ? outer : inner;
    const x0=lonToX(b.w,z), x1=lonToX(b.e,z), y0=latToY(b.n,z), y1=latToY(b.s,z);
    const max = Math.pow(2,z)-1;
    for (let x=Math.max(0,x0); x<=Math.min(max,x1); x++)
      for (let y=Math.max(0,y0); y<=Math.min(max,y1); y++)
        out.push([z,x,y]);
  }
  return out;
}

/* Download a region.
   We do NOT compute byte offsets ourselves — we simply ask PMTiles for each
   tile. Every such read goes through BlockSource, which pulls a 256 KB block
   and caches it. Because PMTiles clusters tiles in Hilbert order, geographic
   neighbours are file neighbours, so one block fetch satisfies hundreds of
   subsequent tile reads. Thousands of tiles become a few dozen requests. */
async function downloadRegion(lat, lng, miles, onProgress, isCancelled, radiusUnits, userName){
  const url = TILE_URL;
  await checkEtag(url);
  const src = new BlockSource(url);
  const p   = new pmtiles.PMTiles(src);
  await p.getHeader();

  const list = tilesFor(lat,lng,miles);
  const before = await countBlocks(url);
  let done = 0;
  for (const [z,x,y] of list){
    if (isCancelled && isCancelled()){ const e = new Error('cancelled'); e.cancelled = true; throw e; }
    try { await p.getZxy(z,x,y); } catch(e){ /* absent tile: normal */ }
    if (++done % 25 === 0 && onProgress) onProgress(done, list.length);
  }
  if (onProgress) onProgress(list.length, list.length);

  const after = await countBlocks(url);
  const nm = (userName && String(userName).trim()) ? String(userName).trim() : await placeName(lat,lng);
  const rec = {
    id: 'r' + Date.now(),
    name: nm,
    lat, lng,
    miles,                                   // internal (miles) for any math
    radius: radiusUnits != null ? radiusUnits : miles,   // shown to the user, active unit
    unit: UNIT_LABEL,
    bytes: (after.count - before.count) > 0 ? (after.bytes - before.bytes) : after.bytes,
    blocks: after.count - before.count,
    created: Date.now(),
    mapUrl: TILE_URL                         // the map this area was cut from
  };
  if (rec.bytes <= 0) rec.bytes = after.bytes;
  await putRegion(rec);
  return rec;
}


/* ── WHOLE-ARCHIVE SUPPORT ────────────────────────────────────────
   The archive's total size comes back on the Content-Range header of any range
   request, so asking for a single byte tells us how big the whole map is. */
async function archiveSize(url){
  // The whole-archive size is (tile-data offset + tile-data length) from the PMTiles
  // header - the data section is last in the file. Reading it from the header works
  // offline and no matter which blocks are cached, unlike a Content-Range probe.
  try {
    const src = new BlockSource(url || TILE_URL);
    const p   = new pmtiles.PMTiles(src);
    const h   = await p.getHeader();
    if (h && h.tileDataOffset != null && h.tileDataLength != null)
      return h.tileDataOffset + h.tileDataLength;
  } catch (e) {}
  try { const r = await fetchRange(url || TILE_URL, 0, 0); return r.total || 0; } catch (e) { return 0; }
}

/* Download EVERY block of the archive, so the whole map is available offline at
   all zoom levels. Uses the same 256 KB block cache as a region download - it is
   simply "fetch all the blocks" rather than "fetch the blocks these tiles need". */
async function downloadWholeArchive(onProgress, isCancelled, userName){
  const url = TILE_URL;
  await checkEtag(url);
  const total = await archiveSize(url);
  if (!total) throw new Error('Could not determine the map size');
  const nBlocks = Math.ceil(total / BLOCK);
  for (let b = 0; b < nBlocks; b++){
    if (isCancelled && isCancelled()){ const e = new Error('cancelled'); e.cancelled = true; throw e; }
    let buf = await getBlock(url, b);
    if (!buf){
      const end = Math.min((b + 1) * BLOCK, total) - 1;
      const r = await fetchRange(url, b * BLOCK, end);
      if (r.complete){ try { await putBlock(url, b, r.buf); } catch(e){} }
    }
    if (onProgress && ((b + 1) % 4 === 0)) onProgress(b + 1, nBlocks);
  }
  if (onProgress) onProgress(nBlocks, nBlocks);
  const after = await countBlocks(url);
  const rec = {
    id: 'r' + Date.now(),
    name: (userName && String(userName).trim()) ? String(userName).trim() : 'Entire map',
    lat: null, lng: null, miles: null,
    radius: null, unit: UNIT_LABEL,
    whole: true,
    bytes: after.bytes,
    blocks: after.count,
    created: Date.now(),
    mapUrl: TILE_URL                         // the map this area was cut from
  };
  await putRegion(rec);
  return rec;
}

/* The geographic extent the archive actually covers, from its header. */
async function archiveBounds(){
  const src = new BlockSource(TILE_URL);
  const p   = new pmtiles.PMTiles(src);
  const h   = await p.getHeader();
  if (h == null || h.minLon == null || h.maxLon == null) return null;
  return { minLon: h.minLon, minLat: h.minLat, maxLon: h.maxLon, maxLat: h.maxLat };
}

/* Hard-stop the zoom-out at the archive's coverage. A bbox extract contains only
   the tiles overlapping its box, so at low zooms the sibling tiles simply do not
   exist and the map renders as fragments against white. Rather than show that, we
   refuse to zoom out past the point where the covered area fills the view. */
function applyMinZoom(map){
  const L = global.L;
  if (!L) return;
  archiveBounds().then(b => {
    if (!b) return;
    const bounds = L.latLngBounds([[b.minLat, b.minLon], [b.maxLat, b.maxLon]]);
    const fit = () => {
      if (map._fhMinZoomLifted) return;   // v72.10: hunt.html lifted the floor while outside coverage
      try {
        const z = map.getBoundsZoom(bounds, false);
        if (!isFinite(z)) return;
        const mz = Math.max(0, Math.floor(z));
        map.setMinZoom(mz);
        if (map.getZoom() < mz) map.setZoom(mz);
      } catch(e){}
    };
    fit();
    map.on('resize', fit);          // container size changes the answer
  }).catch(() => {});
}

async function countBlocks(url){
  const d = await idb();
  return new Promise((res,rej)=>{
    const t = d.transaction('blocks','readonly'), s = t.objectStore('blocks');
    let count=0, bytes=0;
    const c = s.openCursor();
    c.onsuccess = e => {
      const cur = e.target.result;
      if (!cur) return res({count, bytes});
      if (String(cur.key).startsWith(url + '|')) { count++; bytes += (cur.value.byteLength||0); }
      cur.continue();
    };
    c.onerror = () => rej(c.error);
  });
}

/* If the hosted archive has been REPLACED, its internal byte offsets change and
   old cached blocks would splice into new ones and render garbage. The ETag
   tells us; on a change we purge everything and start clean. */
// Returns TRUE if it purged, so a caller that is already reading the archive can
// rebuild itself. See addBasemap: purging the cache is not enough on its own,
// because PMTiles holds the header and directories in MEMORY once read, and
// those describe the OLD file's byte layout.
async function checkEtag(url){
  if (!navigator.onLine) return false;

  // cache:'no-store' is essential, not decorative. Map archives are served with a
  // long Cache-Control lifetime (the shipped .htaccess sets max-age=86400), so a
  // plain fetch can be satisfied from the browser's HTTP cache and hand back the
  // OLD ETag. The comparison then finds prev === etag, concludes nothing has
  // changed, and leaves a stale cache in place - which is precisely what happened
  // in v71.9 testing: nothing on the first load, and the purge only firing on the
  // next reload, when Chrome revalidates. This request must always reach the
  // server, and it costs only a few hundred bytes.
  //
  // Retried once, because the check runs alongside a burst of tile requests and a
  // single transient failure would otherwise silently skip the purge until the
  // user happened to reload.
  let etag = null;
  for (let attempt = 0; attempt < 2 && etag === null; attempt++) {
    try {
      const r = await fetch(url, { method:'HEAD', cache:'no-store' });
      if (r && r.ok) etag = r.headers.get('etag');
    } catch(e){ /* transient: fall through and retry once */ }
    if (etag === null && attempt === 0) await new Promise(r => setTimeout(r, 400));
  }
  if (!etag) return false;          // offline, HEAD blocked, or ETag not exposed

  try {
    const prev = await getMeta('etag:' + url);
    let purged = false;
    if (prev && prev !== etag){ await purgeAll(url); await delAllRegions(); purged = true; }
    await putMeta('etag:' + url, etag);
    return purged;
  } catch(e){ return false; }
}
async function purgeAll(url){
  const d = await idb();
  return new Promise((res)=>{
    const t = d.transaction('blocks','readwrite'), s = t.objectStore('blocks');
    const c = s.openCursor();
    c.onsuccess = e => { const cur = e.target.result;
      if (!cur) return; if (String(cur.key).startsWith(url+'|')) cur.delete(); cur.continue(); };
    t.oncomplete = () => res();
  });
}
async function delAllRegions(){
  const rs = await allRegions();
  for (const r of rs) await delRegionRec(r.id);
}

// Best-effort label for a downloaded region: the nearest named place from the
// vector "places" layer at the chosen centre. Offline-friendly (reads the tiles
// we already have), no network geocoder. Falls back to coordinates if nothing
// named is close. This is only a SUGGESTED name — the user can overwrite it.
async function placeName(lat,lng){
  const coords = lat.toFixed(2) + ', ' + lng.toFixed(2);
  try {
    const src = new BlockSource(TILE_URL);
    const p = new pmtiles.PMTiles(src);
    const P = global.protomapsL;
    const source = new P.PmtilesSource(p, false);
    // Query the places layer at a mid zoom around the point.
    const Z = 11, N = Math.pow(2, Z), EXT = 4096;
    const x = Math.floor((lng + 180) / 360 * N);
    const yr = lat * Math.PI / 180;
    const y = Math.floor((1 - Math.log(Math.tan(yr) + 1/Math.cos(yr)) / Math.PI) / 2 * N);
    let best = null, bestD = Infinity;
    // Check the tile the point is in and its 8 neighbours, in case the point sits
    // near a tile edge and the nearest town is just across it.
    for (let dx = -1; dx <= 1; dx++) for (let dy = -1; dy <= 1; dy++){
      let layers; try { layers = await source.get({z:Z, x:x+dx, y:y+dy}, EXT); } catch(e){ continue; }
      const pl = layers.get('places'); if (!pl) continue;
      for (const f of pl){
        if (!f.props || !f.props.name) continue;
        const bb = f.bbox, cx = (bb.minX+bb.maxX)/2, cy = (bb.minY+bb.maxY)/2;
        const flon = (x+dx + cx/EXT)/N*360 - 180;
        const nn = Math.PI - 2*Math.PI*(y+dy + cy/EXT)/N;
        const flat = 180/Math.PI*Math.atan(0.5*(Math.exp(nn)-Math.exp(-nn)));
        // Nearest named place wins, by squared degree distance. Place rank
        // (city > town > hamlet) is NOT considered — it's only a suggested
        // name, and the user can overwrite it.
        const d = (flat-lat)*(flat-lat) + (flon-lng)*(flon-lng);
        if (d < bestD){ bestD = d; best = f.props.name; }
      }
    }
    return best || coords;
  } catch(e){ return coords; }
}

async function storageInfo(){
  if (!navigator.storage || !navigator.storage.estimate) return null;
  try {
    const e = await navigator.storage.estimate();
    return { usage:e.usage||0, quota:e.quota||0 };
  } catch(e){ return null; }
}
async function requestPersist(){
  if (navigator.storage && navigator.storage.persist){
    try { return await navigator.storage.persist(); } catch(e){}
  }
  return false;
}
