/* ═══════════════════════════════════════════════════════════════════
   FOX PURSUIT — MAP  (v60)

   Replaces the old OpenStreetMap raster tiles with a VECTOR basemap read
   from a single .pmtiles archive over HTTP range requests.

   Three things live in here:

     1. THE STYLE      how the map is drawn (foxhunt-map-style below).
     2. OFFLINE CACHE  a block cache in IndexedDB, so a downloaded region
                       keeps working with no signal.
     3. REGION UI      pick a centre + radius, download it, manage it.

   WHY A BLOCK CACHE, NOT A TILE CACHE
   PMTiles stores its tiles in Hilbert-curve order, which means tiles that
   are near each other on the ground are near each other IN THE FILE. So we
   cache fixed-size BLOCKS of the archive rather than individual tiles: one
   256 KB block fetch typically brings in a couple of hundred neighbouring
   tiles at once. A region download is therefore a few dozen HTTP requests,
   not several thousand, and ordinary online panning warms the same cache
   for free.

   NOTHING HERE IS HOST-OWNED. Host settings live in 0-config-foxhunt.js
   (tileUrl, units, mapRegionRadii). Do not edit this file to configure a site.
   ═══════════════════════════════════════════════════════════════════ */
