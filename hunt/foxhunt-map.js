// The live basemap layer, so it can be redrawn from outside. Reassigned when
// the ETag check rebuilds the layer, so this handle never goes stale.
let _basemapLayer = null;

const FoxMap = {
  TILE_URL, RADII, DATA_MAXZOOM,
  // Unit info for the UI. RADII and CONTEXT_DIST are already in the active unit;
  // UNIT_METERS converts an active-unit value to metres (for Leaflet, which is
  // metric-only). CONTEXT_MILES is the miles value used internally.
  UNITS, UNIT_LABEL, IS_METRIC, UNIT_METERS, CONTEXT_DIST, CONTEXT_MILES,

  // True when tileUrl has been configured (not blank, not the placeholder).
  TILE_URL_OK,

  // Create the vector basemap layer and add it to a Leaflet map.
  addBasemap(map){
    if (!TILE_URL_OK) { showNotConfigured(map); return null; }
    const P = global.protomapsL;

    // One basemap layer, with its own BlockSource and PMTiles instance. Built as
    // a function because it may need building twice - see the rebuild below.
    const build = () => {
      const pm    = new pmtiles.PMTiles(new BlockSource(TILE_URL));
      const layer = P.leafletLayer({
        url: pm,
        paintRules: paintRules(P),
        labelRules: labelRules(P),
        backgroundColor: C.earth,
        maxDataZoom: DATA_MAXZOOM,
        attribution: '<a href="https://protomaps.com">Protomaps</a> © <a href="https://openstreetmap.org">OpenStreetMap</a>'
      });
      layer.addTo(map);
      // A set-but-unreadable tileUrl (wrong path, 404, corrupt) renders blank with
      // no explanation. Probe the header; if it can't be read, say so plainly.
      // Reuses the layer's own PMTiles instance rather than building a second one.
      (async () => {
        const probe = async () => { await pm.getHeader(); return true; };
        try { await probe(); }
        catch (e) { showLoadFailed(map, TILE_URL, probe); }
      })();
      return layer;
    };

    let layer = build();
    _basemapLayer = layer;
    applyMinZoom(map);

    // The staleness check runs alongside, not before, so a normal load never
    // waits on a network round-trip to draw the map.
    //
    // But if the hosted archive HAS been replaced, purging the block cache is
    // only half the job: this layer's PMTiles instance has already read the old
    // header and directories into memory, and will keep asking for byte offsets
    // that no longer mean anything. Before v71.9 that left a broken map until
    // the user happened to reload - the tiles simply failed to fetch.
    //
    // So on a purge, throw the layer away and build a fresh one, which reads the
    // new header from the now-empty cache. Only the rare replaced-archive case
    // pays anything; every ordinary load is untouched.
    checkEtag(TILE_URL).then(purged => {
      if (!purged) return;
      console.info('[Fox Pursuit] map archive replaced — cache cleared, reloading the basemap.');
      try { map.removeLayer(layer); } catch (e) {}
      layer = build();
      _basemapLayer = layer;
    }).catch(() => {});

    return layer;
  },

  // Re-request every visible tile of the current basemap. Used when the
  // connection returns: tiles that failed while offline are left in place by
  // Leaflet as blank tiles until something forces a redraw (v72.5). A failed
  // fetch is never cached by the tile layer, so redraw() refetches them.
  redrawBasemap(){
    try { if (_basemapLayer && typeof _basemapLayer.redraw === 'function') _basemapLayer.redraw(); } catch (e) {}
  },

  tilesFor, allRegions, storageInfo, requestPersist, fmtMB,

  // Whole-archive offline download. WHOLE_MAX is the size above which the UI
  // should discourage it: a very large archive runs into phone storage and
  // browser eviction long before it runs out of patience.
  WHOLE_MAX: 100 * 1024 * 1024,
  MAP_URL: TILE_URL,
  archiveSize, archiveBounds, detailBounds,
  downloadWholeArchive(onProgress, isCancelled, userName){
    return downloadWholeArchive(onProgress, isCancelled, userName);
  },


  // radiusUnits is in the ACTIVE unit (mi or km). Convert to miles for the
  // internal tile math, and record the unit on the saved region. userName, if
  // given, is used verbatim; otherwise a nearest-place name is derived.
  downloadRegion(lat, lng, radiusUnits, onProgress, isCancelled, userName){
    return downloadRegion(lat, lng, radiusUnits * UNIT_TO_MI, onProgress, isCancelled, radiusUnits, userName);
  },

  // Suggested name for a point (nearest named place), for pre-filling the prompt.
  suggestName(lat, lng){ return placeName(lat, lng); },

  // FP12 (2026-10-03): one browser site can hold several Fox Pursuit apps (Solo at
  // /solo beside Team sites at /demo, /test) and they share this store. Delete and
  // Delete all therefore act only on areas cut from THIS app's map: another app's
  // areas, or areas of a map not in use here, are never touched from here.
  async deleteRegion(id){
    const rs = await allRegions();
    await delRegionRec(id);
    const left = rs.filter(r => r.id !== id && r.mapUrl === TILE_URL);
    if (!left.length) await purgeAll(TILE_URL);
  },

  async clearAll(){
    const rs = await allRegions();
    for (const r of rs) if (r.mapUrl === TILE_URL) await delRegionRec(r.id);
    await purgeAll(TILE_URL);
  },

  // radiusUnits in the ACTIVE unit; convert to miles for the tile count.
  async estimateBytes(lat,lng,radiusUnits){
    const list = tilesFor(lat,lng,radiusUnits * UNIT_TO_MI);
    return { tiles: list.length, bytes: Math.round(list.length * 1400) };
  }
};

